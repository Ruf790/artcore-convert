def set_lang(lang: str) -> None:
    global _lang
    _lang = "en" if lang == "en" else "ru"


def lang() -> str:
    return _lang


def t(key: str, *args) -> str:
    pair = STRINGS.get(key)
    if pair is None:
        return key
    s = pair[0] if _lang == "ru" else pair[1]
    return s.format(*args) if args else s
